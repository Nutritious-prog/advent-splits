// Writes supabase/seed.sql so the challenge pool can be pasted into the Supabase SQL editor.
import fs from "node:fs";
import { ALL_CHALLENGES } from "../lib/challenges";

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lines = ALL_CHALLENGES.map((c) =>
  `(${[c.id, c.category, c.title, c.teaser, c.description].map(lit).join(", ")}, ${lit(JSON.stringify(c.steps))}::jsonb, ${lit(c.tips)}, ${lit(c.difficulty)}, ${c.minutes}, ${lit(JSON.stringify(c.equipment))}::jsonb, ${[c.gear, c.icon, c.easier, c.harder, c.safety, c.caption, c.resultType, c.resultUnit].map(lit).join(", ")})`,
);
const sql = `-- Generated by scripts/export-seed-sql.ts — ${ALL_CHALLENGES.length} challenges.
insert into challenges (id, category, title, teaser, description, steps, tips, difficulty, minutes, equipment, gear, icon, easier, harder, safety, caption, result_type, result_unit) values
${lines.join(",\n")}
on conflict (id) do nothing;
`;
fs.writeFileSync("supabase/seed.sql", sql);
console.log(`wrote supabase/seed.sql (${ALL_CHALLENGES.length} rows)`);
